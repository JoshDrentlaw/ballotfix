/**
 * Storage for the web app: runs, ballots, and the voter's choices, each a
 * table in one SQLite file (src/web/db.ts), plus the knowledge graph derived
 * from finished runs (src/web/kb.ts). Until this replaced them, each record
 * was a JSON file in the data directory; openStores() imports those once.
 */

import { notesToReuse } from "../context.ts";
import { scopeKey } from "../knowledge.ts";
import { type KnownOffice, officeKey, reusable } from "../office.ts";
import { Db } from "./db.ts";
import { KnowledgeBase } from "./kb.ts";
import type {
  BallotCandidate,
  BallotReading,
  CandidateSource,
  ContextNote,
  MeasureDossier,
  MeasureQuery,
  RaceDossier,
  RaceQuery,
} from "../types.ts";

export type RunStatus = "queued" | "running" | "done" | "failed" | "interrupted";

/**
 * One research run: a race between candidates, or (when `measure` is set) one
 * ballot measure. A measure run's `query` holds its jurisdiction as the city
 * and its label as the office, so listings and ids work the same way.
 */
export interface RunRecord {
  id: string;
  query: RaceQuery;
  /** Set for a measure run; absent or null for a race. */
  measure?: MeasureQuery | null;
  /** Issues the voter said matter most to them; absent or [] when none. */
  priorities?: string[];
  /** Where the voter's notes and pick for this are kept; carried over on rerun. Default: id. */
  choice_id?: string;
  /** The ballot item this was started from, if any. */
  ballot?: BallotLink | null;
  /** Candidate list the user supplied, if any; null means ballot discovery. */
  candidates: BallotCandidate[] | null;
  /** Where `candidates` came from; absent or null means typed in by the user. */
  candidate_source?: CandidateSource | null;
  status: RunStatus;
  created_at: string;
  updated_at: string;
  error: string | null;
  /** Partial while running, complete when done; null until the ballot is known. */
  race: RaceDossier | null;
  /** A measure run's result: pending while running. */
  measure_result?: MeasureDossier | null;
}

export interface BallotLink {
  id: string;
  /** Key in BallotRecord.started: a contest's index, or m<index> for a measure. */
  key: string;
  vote_for: number | null;
}

/** Ids are generated by the app; anything else is refused before it touches the filesystem. */
const ID_RE = /^[a-z0-9][a-z0-9-]{0,119}$/;

export function isRunId(id: string): boolean {
  return ID_RE.test(id);
}

type Table = "runs" | "ballots" | "choices";

/**
 * One row per record, its body the record as JSON. Shared by runs, ballots,
 * and choices. Runs and ballots also copy their status into an indexed
 * column, so the startup checks don't parse every record.
 */
class RecordTable<T extends { id: string; created_at: string }> {
  constructor(readonly db: Db, readonly table: Table, readonly hasStatus: boolean) {}

  /**
   * The one write path. "update" upserts with ON CONFLICT DO UPDATE, never
   * REPLACE, which would delete the row (and cascade to its graph rows)
   * first. "keep" leaves an existing row alone. Returns rows changed.
   */
  protected write(record: T, onConflict: "update" | "keep"): number {
    if (!isRunId(record.id)) throw new Error(`invalid id: ${record.id}`);
    const st = this.hasStatus;
    return this.db.run(
      `INSERT INTO ${this.table} (id, created_at, ${st ? "status, " : ""}body)
       VALUES (?, ?, ${st ? "?, " : ""}?) ON CONFLICT (id) DO ${
        onConflict === "keep"
          ? "NOTHING"
          : `UPDATE SET ${st ? "status = excluded.status, " : ""}body = excluded.body`
      }`,
      record.id,
      record.created_at,
      ...(st ? [String((record as { status?: unknown }).status)] : []),
      JSON.stringify(record),
    );
  }

  save(record: T): Promise<void> {
    try {
      this.write(record, "update");
      return Promise.resolve();
    } catch (err) {
      return Promise.reject(err);
    }
  }

  /** Adds a record unless one with its id exists. True when it was added. */
  insertIfAbsent(record: T): boolean {
    return this.write(record, "keep") > 0;
  }

  get(id: string): Promise<T | null> {
    if (!isRunId(id)) return Promise.resolve(null);
    const r = this.db.get(`SELECT body FROM ${this.table} WHERE id = ?`, id);
    return Promise.resolve(r ? parse<T>(r.body) : null);
  }

  /** All records, newest first. Unreadable rows are skipped, not fatal. */
  list(): Promise<T[]> {
    const rows = this.db.all(`SELECT body FROM ${this.table} ORDER BY created_at DESC, id`);
    return Promise.resolve(rows.map((r) => parse<T>(r.body)).filter((r): r is T => r !== null));
  }

  /** Records whose status column is `status`. Needs hasStatus. */
  protected withStatus(...statuses: string[]): T[] {
    const rows = this.db.all(
      `SELECT body FROM ${this.table} WHERE status IN (${statuses.map(() => "?").join(", ")})`,
      ...statuses,
    );
    return rows.map((r) => parse<T>(r.body)).filter((r): r is T => r !== null);
  }
}

function parse<T>(body: unknown): T | null {
  try {
    return JSON.parse(String(body)) as T;
  } catch {
    return null;
  }
}

export class RunStore extends RecordTable<RunRecord> {
  readonly knowledge: KnowledgeBase;
  readonly #log: (msg: string) => void;

  constructor(db: Db, log: (msg: string) => void = () => {}) {
    super(db, "runs", true);
    this.knowledge = new KnowledgeBase(db);
    this.#log = log;
  }

  /**
   * Saving a run also refreshes what it contributes to the knowledge graph,
   * in the same transaction (one disk sync). Indexing runs in a savepoint: if
   * it fails, only the graph's share is undone and logged, never the run,
   * which is the record of research already paid for. Only a finished run
   * contributes, so the partial saves made while research runs stay cheap.
   */
  override save(run: RunRecord): Promise<void> {
    try {
      this.db.tx(() => {
        this.write(run, "update");
        try {
          this.knowledge.indexRun(run);
        } catch (err) {
          this.#log(`Could not add run ${run.id} to the knowledge graph: ${err}`);
          // Don't leave an earlier version of this run in the graph. A rebuild repairs the rest.
          this.knowledge.forgetRun(run.id);
        }
      });
      return Promise.resolve();
    } catch (err) {
      return Promise.reject(err);
    }
  }

  /**
   * The newest finished run of the same race or measure (same choice id)
   * started after this one: what a rerun replaced it with. Null if none.
   */
  newerDone(run: RunRecord): string | null {
    const r = this.db.get(
      `SELECT id FROM runs WHERE status = 'done' AND id != ?1 AND created_at > ?2
       AND coalesce(CASE WHEN json_valid(body) THEN json_extract(body, '$.choice_id') END, id) = ?3
       ORDER BY created_at DESC, id LIMIT 1`,
      run.id,
      run.created_at,
      run.choice_id ?? run.id,
    );
    return r ? String(r.id) : null;
  }

  /**
   * Verified context notes held by finished runs in one place (state +
   * jurisdiction, compared as the graph compares them), newest run first:
   * what the context step can reuse instead of looking up again
   * (src/context.ts). A measure run keeps its jurisdiction as the city.
   *
   * Never from `except`'s own race or measure (same choice id: the run itself
   * and every earlier run a rerun replaces), even by way of another run that
   * reused one of them, so a rerun looks its names up afresh.
   */
  knownNotes(state: string, jurisdiction: string, except: string): ContextNote[] {
    const scope = scopeKey(state, jurisdiction);
    const done = this.withStatus("done");
    const raceOf = (r: RunRecord) => r.choice_id ?? r.id;
    const self = done.find((r) => r.id === except);
    const own = new Set(
      done.filter((r) => r.id === except || (self && raceOf(r) === raceOf(self))).map((r) => r.id),
    );
    own.add(except);
    return done
      .filter((r) => !own.has(r.id) && scopeKey(r.query.state, r.query.city) === scope)
      .sort((a, b) => b.updated_at.localeCompare(a.updated_at))
      .flatMap((r) => notesToReuse(r.measure_result?.context ?? r.race?.context, r))
      .filter((n) => !own.has(n.reused_from!.run));
  }

  /**
   * The newest reusable office lookup (src/office.ts `reusable`) a finished race
   * other than `except` holds for the same office in the same place, keyed as
   * `officeKey` compares them. Null when none is recent enough to reuse.
   */
  knownOffice(query: RaceQuery, except: string, now: Date): KnownOffice | null {
    const key = officeKey(query.state, query.city, query.office);
    const found = this.withStatus("done")
      .filter((r) =>
        r.id !== except && r.race?.office &&
        officeKey(r.query.state, r.query.city, r.race.office.office) === key
      )
      .map((r) => ({ r, k: reusable(r.race!.office, r, now) }))
      .filter((x): x is { r: RunRecord; k: KnownOffice } => x.k !== null)
      // Newest lookup, not newest run: a run that reused an old lookup shouldn't hide a fresher one.
      .sort((a, b) =>
        b.k.from.looked_up.localeCompare(a.k.from.looked_up) ||
        b.r.updated_at.localeCompare(a.r.updated_at)
      )
      .map((x) => x.k);
    return found[0] ?? null;
  }

  /**
   * Runs submitted but never started, oldest first: on startup they go back
   * in the queue (JobRunner.resume), since nothing has been spent on them yet.
   */
  waiting(): RunRecord[] {
    // Several races from one ballot are often submitted within the same millisecond;
    // rowid (insertion order, kept by the upsert) breaks those ties in submission order.
    const rows = this.db.all(
      `SELECT body FROM runs WHERE status = ? ORDER BY created_at, rowid`,
      "queued",
    );
    return rows.map((r) => parse<RunRecord>(r.body)).filter((r): r is RunRecord => r !== null);
  }

  /**
   * A run that was running when the server stopped will never finish. Say so
   * rather than leaving it spinning forever. Not restarted: research already
   * paid for part of it, so whether to pay again is the voter's call (rerun).
   */
  async markInterrupted(now: string): Promise<number> {
    let n = 0;
    for (const run of this.withStatus("running")) {
      await this.save({
        ...run,
        status: "interrupted",
        updated_at: now,
        error: "The server restarted before this research finished.",
      });
      n++;
    }
    return n;
  }
}

export type BallotStatus = "reading" | "read" | "failed" | "interrupted";

/**
 * An uploaded ballot. Only what was read from it is kept: the photos and
 * PDFs themselves are never written to disk.
 */
export interface BallotRecord {
  id: string;
  status: BallotStatus;
  created_at: string;
  updated_at: string;
  error: string | null;
  /** How many photos or PDFs were uploaded. */
  pages: number;
  reading: BallotReading | null;
  /** Race runs started from this ballot, by contest index. */
  started: Record<string, string>;
}

export class BallotStore extends RecordTable<BallotRecord> {
  constructor(db: Db) {
    super(db, "ballots", true);
  }

  async markInterrupted(now: string): Promise<number> {
    let n = 0;
    for (const b of this.withStatus("reading")) {
      await this.save({
        ...b,
        status: "interrupted",
        updated_at: now,
        error: "The server restarted before this ballot was read. Upload it again.",
      });
      n++;
    }
    return n;
  }
}

/**
 * The voter's own notes and preliminary pick for one contest or measure.
 * Kept apart from runs so a research job saving progress can't overwrite
 * them, and never included in downloaded pages.
 */
export interface ChoiceRecord {
  id: string;
  created_at: string;
  updated_at: string;
  /** Candidate names, or "Yes"/"No" for a measure or retention question. [] is undecided. */
  picks: string[];
  notes: string;
}

export class ChoiceStore extends RecordTable<ChoiceRecord> {
  constructor(db: Db) {
    super(db, "choices", false);
  }
}

export interface Stores {
  db: Db;
  runs: RunStore;
  ballots: BallotStore;
  choices: ChoiceStore;
}

export interface OpenOptions {
  log?: (msg: string) => void;
}

/**
 * Opens (or creates) data/ballotfix.db. On first open, imports the JSON
 * files earlier versions kept in the same directory (runs at the top level,
 * ballots/ and choices/ below), leaving the files in place. Rebuilds the
 * knowledge graph when its projection changed or records were imported.
 */
export async function openStores(dir: string, opts: OpenOptions = {}): Promise<Stores> {
  const log = opts.log ?? (() => {});
  await Deno.mkdir(dir, { recursive: true });
  const db = new Db(`${dir}/ballotfix.db`);
  const stores: Stores = {
    db,
    runs: new RunStore(db, log),
    ballots: new BallotStore(db),
    choices: new ChoiceStore(db),
  };
  let imported = 0;
  if (db.meta("json_imported_at") === null) {
    const runs = await readJsonDir<RunRecord>(dir, true);
    const ballots = await readJsonDir<BallotRecord>(`${dir}/ballots`, true);
    const choices = await readJsonDir<ChoiceRecord>(`${dir}/choices`, false);
    db.tx(() => {
      // Any existing row is newer than the file it came from, so it is kept.
      for (const r of runs) if (stores.runs.insertIfAbsent(r)) imported++;
      for (const r of ballots) if (stores.ballots.insertIfAbsent(r)) imported++;
      for (const r of choices) if (stores.choices.insertIfAbsent(r)) imported++;
      db.setMeta("json_imported_at", new Date().toISOString());
    });
    if (imported) {
      log(`Imported ${imported} saved record(s) from JSON files into ${dir}/ballotfix.db.`);
    }
  }
  if (imported || !stores.runs.knowledge.upToDate) {
    const { indexed, skipped } = stores.runs.knowledge.rebuild(log);
    if (indexed || skipped) {
      log(`Indexed ${indexed} finished run(s) into the knowledge graph; skipped ${skipped}.`);
    }
  }
  return stores;
}

/**
 * The *.json records in one directory, skipping anything unreadable,
 * misnamed, or (for a table with a status column) without a status.
 */
async function readJsonDir<T extends { id: string; created_at: string }>(
  dir: string,
  needsStatus: boolean,
): Promise<T[]> {
  const out: T[] = [];
  try {
    for await (const e of Deno.readDir(dir)) {
      if (!e.isFile || !e.name.endsWith(".json")) continue;
      const id = e.name.slice(0, -5);
      if (!isRunId(id)) continue;
      const r = parse<Record<string, unknown>>(await Deno.readTextFile(`${dir}/${e.name}`));
      if (
        r && typeof r === "object" && r.id === id && typeof r.created_at === "string" &&
        (!needsStatus || typeof r.status === "string")
      ) {
        out.push(r as unknown as T);
      }
    }
  } catch (err) {
    if (!(err instanceof Deno.errors.NotFound)) throw err;
  }
  return out;
}
