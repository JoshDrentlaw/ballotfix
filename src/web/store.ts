/**
 * Run storage for the web app: one JSON file per research run in a data
 * directory. Phase 0 deliberately has no database; a run is small and
 * written a handful of times.
 */

import type {
  BallotCandidate,
  BallotReading,
  CandidateSource,
  MeasureDossier,
  MeasureQuery,
  RaceDossier,
  RaceQuery,
} from "../types.ts";

export type RunStatus = "queued" | "running" | "done" | "failed" | "interrupted";

/**
 * One research run: a race between candidates, or (when `measure` is set) one
 * ballot measure. A measure run's `query` holds its jurisdiction as the city
 * and its label as the office, so listings and ids work the same way.
 */
export interface RunRecord {
  id: string;
  query: RaceQuery;
  /** Set for a measure run; absent or null for a race. */
  measure?: MeasureQuery | null;
  /** Issues the voter said matter most to them; absent or [] when none. */
  priorities?: string[];
  /** Where the voter's notes and pick for this are kept; carried over on rerun. Default: id. */
  choice_id?: string;
  /** The ballot item this was started from, if any. */
  ballot?: BallotLink | null;
  /** Candidate list the user supplied, if any; null means ballot discovery. */
  candidates: BallotCandidate[] | null;
  /** Where `candidates` came from; absent or null means typed in by the user. */
  candidate_source?: CandidateSource | null;
  status: RunStatus;
  created_at: string;
  updated_at: string;
  error: string | null;
  /** Partial while running, complete when done; null until the ballot is known. */
  race: RaceDossier | null;
  /** A measure run's result: pending while running. */
  measure_result?: MeasureDossier | null;
}

export interface BallotLink {
  id: string;
  /** Key in BallotRecord.started: a contest's index, or m<index> for a measure. */
  key: string;
  vote_for: number | null;
}

/** Ids are generated by the app; anything else is refused before it touches the filesystem. */
const ID_RE = /^[a-z0-9][a-z0-9-]{0,119}$/;

export function isRunId(id: string): boolean {
  return ID_RE.test(id);
}

/** One JSON file per record in a directory, keyed by a validated id. Shared by runs and ballots. */
class JsonDir<T extends { id: string; created_at: string }> {
  constructor(readonly dir: string) {}

  #path(id: string): string {
    if (!isRunId(id)) throw new Error(`invalid id: ${id}`);
    return `${this.dir}/${id}.json`;
  }

  async init(): Promise<void> {
    await Deno.mkdir(this.dir, { recursive: true });
  }

  /** Atomic save: write a temp file, then rename over the old one. */
  async save(record: T): Promise<void> {
    const path = this.#path(record.id);
    const tmp = `${path}.${crypto.randomUUID()}.tmp`;
    await Deno.writeTextFile(tmp, JSON.stringify(record));
    await Deno.rename(tmp, path);
  }

  async get(id: string): Promise<T | null> {
    if (!isRunId(id)) return null;
    try {
      return JSON.parse(await Deno.readTextFile(this.#path(id))) as T;
    } catch (err) {
      if (err instanceof Deno.errors.NotFound || err instanceof SyntaxError) return null;
      throw err;
    }
  }

  /** All records, newest first. Unreadable files are skipped, not fatal. */
  async list(): Promise<T[]> {
    const out: T[] = [];
    try {
      for await (const e of Deno.readDir(this.dir)) {
        if (!e.isFile || !e.name.endsWith(".json")) continue;
        const r = await this.get(e.name.slice(0, -5));
        if (r) out.push(r);
      }
    } catch (err) {
      if (!(err instanceof Deno.errors.NotFound)) throw err;
    }
    return out.sort((a, b) => b.created_at.localeCompare(a.created_at));
  }
}

export class RunStore extends JsonDir<RunRecord> {
  /**
   * A run that was queued or running when the server stopped will never
   * finish. Say so rather than leaving it spinning forever.
   */
  async markInterrupted(now: string): Promise<number> {
    let n = 0;
    for (const run of await this.list()) {
      if (run.status !== "queued" && run.status !== "running") continue;
      await this.save({
        ...run,
        status: "interrupted",
        updated_at: now,
        error: "The server restarted before this research finished.",
      });
      n++;
    }
    return n;
  }
}

export type BallotStatus = "reading" | "read" | "failed" | "interrupted";

/**
 * An uploaded ballot. Only what was read from it is kept: the photos and
 * PDFs themselves are never written to disk.
 */
export interface BallotRecord {
  id: string;
  status: BallotStatus;
  created_at: string;
  updated_at: string;
  error: string | null;
  /** How many photos or PDFs were uploaded. */
  pages: number;
  reading: BallotReading | null;
  /** Race runs started from this ballot, by contest index. */
  started: Record<string, string>;
}

/** Ballots live in a subdirectory of the run directory, so RunStore.list() never sees them. */
export class BallotStore extends JsonDir<BallotRecord> {
  constructor(runDir: string) {
    super(`${runDir}/ballots`);
  }

  async markInterrupted(now: string): Promise<number> {
    let n = 0;
    for (const b of await this.list()) {
      if (b.status !== "reading") continue;
      await this.save({
        ...b,
        status: "interrupted",
        updated_at: now,
        error: "The server restarted before this ballot was read. Upload it again.",
      });
      n++;
    }
    return n;
  }
}

/**
 * The voter's own notes and preliminary pick for one contest or measure.
 * Kept apart from runs so a research job saving progress can't overwrite
 * them, and never included in downloaded pages.
 */
export interface ChoiceRecord {
  id: string;
  created_at: string;
  updated_at: string;
  /** Candidate names, or "Yes"/"No" for a measure or retention question. [] is undecided. */
  picks: string[];
  notes: string;
}

export class ChoiceStore extends JsonDir<ChoiceRecord> {
  constructor(runDir: string) {
    super(`${runDir}/choices`);
  }
}
